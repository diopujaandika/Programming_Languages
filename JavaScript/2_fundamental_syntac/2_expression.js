/**
 * EXPRESSION
 * Expression merupakan bagian dari suatu statement.
 * Expression adalah segala sesuatu yang menghasilkan hasil nilai (value).
 * Biasanya dalam suatu statement biasanya terdiri dari setidaknya 1 statement
 * Ciri-ciri
 * 1. Punya hasil/nilai
 * 2. Bisa diinputkan kedalam statement
 * 3. Bisa digunakan di mana pun nilai dibutuhkan
 */

//Contoh 1: 
    3+4;                //Expression: 3+7 dan Value: 7
    Math.max(10, 20);   //Expression: Math.max(10, 20) dan Value: 20

//Contoh 2:
    const result =  3+ 4;   //Expression: 3 + 4, dan Value: 7 akan tetapi
    console.log(result);    //Expression menjadi Function call expression: console.log(result), karena Expression argumen: result menyimpan Value: 7
