/**
 * OPERATOR & OPERAN
 * Operator adalah simbol atau teks yang digunakan untuk malakukan sebuah operasi.
 * Operan adalah nilai yang menjadi target dari sebuah operasi.
 * 
 * Secara umum dalam JS, operator dikelompokkan berdasarkan jumlah operandnya menjadi 3 kelompok, yaitu:
 * 1. Unary: 1 Operand
 * 2. Binary: 2 Operand
 * 3. Ternary: 3 Operand
 * 
 * Sedangkan berdasarkan fungsinya operator terdapat beberapa macam, yaitu:
 * 1. Assignment
 * 2. Arithmetic
 * 3. Comparison
 * 4. Logic
 * 5. String
 */

//Contoh
    typeof 'Puja Indonesia' //typeof adalah operator dan 'Puja Indonesia' adalah Operand
    5 + 4 // 5 & 4 adalah Operand | + adalah Operator
    10 < 6 // 10 & 6 adalah Operand | < adalah Operator
